// DNS 接管(档案 dns.mode = dnsmasq):dnsmasq 仍是局域网的 DNS 和 DHCP,只把它的上游换成内核的 DNS 入站,
// 本地主机名、DHCP 名字照常由 dnsmasq 自己答。做法是在 dnsmasq 读取的配置目录里放一个带标记的小文件:
//
//	no-resolv
//	server=127.0.0.1#7853
//
// dns.mode 为 off 或 hijack 时后端不动系统:hijack 的劫持是内核自己的 tun(auto_redirect / dns_mode)做的,
// 所以这两种模式对这里的意思都是「撤销」。
//
// 变更安全(DESIGN 第四节):
//   - 不确定就不动:配置目录只从 dnsmasq 自己的主配置里读(OpenWrt 的 /var/etc/dnsmasq.conf.*、Debian 的
//     /etc/dnsmasq.conf 和 /etc/default/dnsmasq),读不到就报「不支持」,不去猜目录,也不碰 UCI
//     (UCI 是持久配置,后端崩溃后会让路由器一直指着一个不在了的内核);
//   - 应用前先确认内核的 DNS 入站有应答,否则一个字都不改;
//   - 先把「要写哪些文件」记进状态文件,再写文件、重启 dnsmasq——中途崩溃也知道该清什么;
//   - 重启后探测 dnsmasq 是否还会答 DNS,不会就自动撤销并重启回去;
//   - 撤销只删带标记的文件,同名的别人的文件不碰;撤销可重复执行;
//   - Recover 给进程启动时用:清掉上次异常退出遗留的接管。
//
// 查询日志(DNS 过滤页的「查询记录」要读它):QueryLog 不为空时,接管文件里再放两行
//
//	log-queries
//	log-facility=<QueryLog>
//
// 让 dnsmasq 把查询日志写进这个文件(默认放内存盘,见 DefaultDNSQueryLog)。同样可回滚、撤销时一起撤掉,另外:
//   - 用户自己已经在 dnsmasq 配置里设了 log-queries / log-facility 就不加,也不覆盖(记为 user);
//   - 日志文件所在目录不存在、或加了日志之后 dnsmasq 起不来:去掉日志那两行再来一次,接管本身照做(记为 failed);
//     failed 记在状态文件里,直到下一次撤销前不再重试,免得每次部署都重启一遍 dnsmasq。

const (
	// TakeoverFileName 是放进 dnsmasq 配置目录的文件名(以 .conf 结尾,通得过常见的 *.conf 过滤)。
	TakeoverFileName = "openbox-dns.conf"
	takeoverMarker   = "# openbox-dns-takeover: generated by openbox-backend, do not edit."

	// DefaultKernelDNSAddr 是内核的 DNS 入站(core 的常量 DNSInboundPort = 7853,监听 0.0.0.0 或 ::)。
	DefaultKernelDNSAddr = "127.0.0.1:7853"
	// DefaultDnsmasqAddr 是 dnsmasq 在本机上的监听地址。
	DefaultDnsmasqAddr = "127.0.0.1:53"

	takeoverService = "dnsmasq"
	maxConfRead     = 1 << 20
)

// DefaultDnsmasqConfigs 是 dnsmasq 主配置的位置(glob):OpenWrt 每个实例生成一份 /var/etc/dnsmasq.conf.<实例>,
// Debian 是 /etc/dnsmasq.conf。位置依据 OpenWrt 和 Debian 的公开文档,没有在真机上见过,需真机确认(见 STATUS.md)。
var DefaultDnsmasqConfigs = []string{"/var/etc/dnsmasq.conf.*", "/etc/dnsmasq.conf"}

// DefaultDnsmasqDefaults 是 Debian 的 dnsmasq 默认值文件,里面的 CONFIG_DIR 是服务脚本传给 dnsmasq 的 --conf-dir。
const DefaultDnsmasqDefaults = "/etc/default/dnsmasq"

// ErrKernelDNSDown:内核的 DNS 入站(还)没有应答。Apply 在这种情况下一个字都没改;调用方可以等内核起来后重试
// (用 errors.Is 判断)。
var ErrKernelDNSDown = errors.New("内核的 DNS 入站没有应答")

// kernelDNSDownError 保留探测的原始错误文字,同时让 errors.Is(err, ErrKernelDNSDown) 成立。
type kernelDNSDownError struct{ cause error }

func (e *kernelDNSDownError) Error() string        { return e.cause.Error() }
func (e *kernelDNSDownError) Unwrap() error        { return e.cause }
func (e *kernelDNSDownError) Is(target error) bool { return target == ErrKernelDNSDown }

// ErrTakeoverUnsupported:这台机器上做不了接管(没找到 dnsmasq 的配置目录、dnsmasq 没在运行……)。出现时系统没被改动。
var ErrTakeoverUnsupported = errors.New("这台机器上没法接管 DNS")

// TakeoverServices 是接管要用的服务管理操作(*Services 满足它,测试里换假的)。
type TakeoverServices interface {
	Status(ctx context.Context, name string) (ServiceInfo, error)
	Do(ctx context.Context, name, action string) (ActionResult, error)
}

// DNSTakeover 做 dnsmasq 转发接管与撤销。零值字段按注释里的默认值处理,只有 StateFile 和 Services 必填。
type DNSTakeover struct {
	StateFile string // 状态文件,通常 <数据目录>/dns-takeover.json
	Services  TakeoverServices

	KernelAddr   string   // 内核 DNS 入站,默认 DefaultKernelDNSAddr
	DnsmasqAddr  string   // dnsmasq 监听,默认 DefaultDnsmasqAddr
	MainConfigs  []string // 主配置 glob,默认 DefaultDnsmasqConfigs
	DefaultsFile string   // 默认 DefaultDnsmasqDefaults
	// QueryLog 是让 dnsmasq 写查询日志的文件(绝对路径);空 = 不开查询日志。
	QueryLog string

	Probe      func(ctx context.Context, addr string) error           // 默认 ProbeDNS
	WriteFile  func(path string, data []byte, perm os.FileMode) error // 默认 store.WriteFileAtomic
	HealthWait time.Duration                                          // 重启后等 dnsmasq 应答的上限,默认 10 秒
	Now        func() time.Time

	mu sync.Mutex
}

// TakeoverStatus 是只读的现状(给以后的状态接口用)。
type TakeoverStatus struct {
	Supported bool     // 找得到可用的配置目录且 dnsmasq 在运行
	Reason    string   // 不支持时的原因
	Dirs      []string // 会放文件的配置目录
	Applied   bool     // 接管文件在、内容对
	Warnings  []string // 例如主配置里还有别的全局上游(它们会让一部分查询绕过内核)
}

type takeoverState struct {
	Version int      `json:"version"`
	Phase   string   `json:"phase"` // applying / applied
	Files   []string `json:"files"`
	Kernel  string   `json:"kernel"`
	At      int64    `json:"at"`
	// Log 是这次让 dnsmasq 写查询日志的文件(空 = 没加);LogSkip 是没加的原因:user / failed(空 = 没有原因)。
	Log     string `json:"log,omitempty"`
	LogSkip string `json:"logSkip,omitempty"`
}

// 没加查询日志的原因,对应前端 DnsFilterQueryLog.reason。
const (
	LogSkipUser   = "user"   // 用户自己在 dnsmasq 里设了日志去向 / log-queries
	LogSkipFailed = "failed" // 目录不存在,或加了日志后 dnsmasq 起不来,已去掉
)

const (
	phaseApplying = "applying"
	phaseApplied  = "applied"
)

func (t *DNSTakeover) kernelAddr() string  { return orDefault(t.KernelAddr, DefaultKernelDNSAddr) }
func (t *DNSTakeover) dnsmasqAddr() string { return orDefault(t.DnsmasqAddr, DefaultDnsmasqAddr) }
func (t *DNSTakeover) mainConfigs() []string {
	if len(t.MainConfigs) > 0 {
		return t.MainConfigs
	}
	return DefaultDnsmasqConfigs
}
func (t *DNSTakeover) defaultsFile() string { return orDefault(t.DefaultsFile, DefaultDnsmasqDefaults) }
func (t *DNSTakeover) healthWait() time.Duration {
	if t.HealthWait > 0 {
		return t.HealthWait
	}
	return 10 * time.Second
}
func (t *DNSTakeover) probe(ctx context.Context, addr string) error {
	if t.Probe != nil {
		return t.Probe(ctx, addr)
	}
	return ProbeDNS(ctx, addr)
}
func (t *DNSTakeover) writeFile(p string, data []byte, perm os.FileMode) error {
	if t.WriteFile != nil {
		return t.WriteFile(p, data, perm)
	}
	return store.WriteFileAtomic(p, data, perm)
}
func (t *DNSTakeover) now() time.Time {
	if t.Now != nil {
		return t.Now()
	}
	return time.Now()
}
func orDefault(v, d string) string {
	if strings.TrimSpace(v) == "" {
		return d
	}
	return v
}

// content 是写进接管文件的内容(不带查询日志)。内核地址拆成 host#port 是 dnsmasq 的 server= 写法。
func (t *DNSTakeover) content() (string, error) { return t.contentFor("") }

// contentFor 是 content 加上查询日志:logPath 不为空时多两行 log-queries 和 log-facility=<文件>(带 / 的是文件名)。
func (t *DNSTakeover) contentFor(logPath string) (string, error) {
	host, port, err := net.SplitHostPort(t.kernelAddr())
	if err != nil {
		return "", fmt.Errorf("内核 DNS 地址不合法: %w", err)
	}
	out := takeoverMarker + "\nno-resolv\nserver=" + host + "#" + port + "\n"
	if logPath != "" {
		out += "log-queries\nlog-facility=" + logPath + "\n"
	}
	return out, nil
}

// validLogPath 检查查询日志路径能不能安全写进 dnsmasq 配置的一行:绝对路径、指向文件、没有空白 / 引号 / # / 逗号 / 反斜杠。
func validLogPath(p string) error {
	switch {
	case !strings.HasPrefix(p, "/"):
		return errors.New("要写成绝对路径")
	case len(p) > 240:
		return errors.New("太长")
	case strings.HasSuffix(p, "/"):
		return errors.New("要指向文件,不是目录")
	}
	for _, c := range p {
		if c <= ' ' || c == 0x7f || strings.ContainsRune("#\"'\\,", c) {
			return errors.New("含有不能写进 dnsmasq 配置的字符")
		}
	}
	return nil
}

// hasLogOption 判断一段 dnsmasq 配置文本有没有设日志选项(log-queries 可以不带值)。注释行不算。
func hasLogOption(text string) bool {
	for _, line := range strings.Split(text, "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		k, _, _ := strings.Cut(line, "=")
		switch strings.TrimSpace(k) {
		case "log-queries", "log-facility":
			return true
		}
	}
	return false
}

// userSetsLogging 只读:dnsmasq 会读的配置(主配置、conf-file= 引进来的文件、配置目录里除接管文件以外的文件)里,
// 用户自己有没有设 log-queries / log-facility。OpenWrt 的 UCI 选项 logqueries / logfacility 会写进生成的主配置,所以也认得出。
// 看不到的:dnsmasq 命令行参数(例如 Debian 的 DNSMASQ_OPTS)。
func (t *DNSTakeover) userSetsLogging(d discovery) bool {
	for _, text := range d.mainTexts {
		if hasLogOption(text) {
			return true
		}
		for _, line := range strings.Split(text, "\n") {
			line = strings.TrimSpace(line)
			if k, v, ok := strings.Cut(line, "="); ok && strings.TrimSpace(k) == "conf-file" {
				if inc := strings.TrimSpace(v); filepath.IsAbs(inc) {
					if b, err := readCapped(inc); err == nil && hasLogOption(b) {
						return true
					}
				}
			}
		}
	}
	for _, cd := range d.dirs {
		entries, err := os.ReadDir(cd.Dir)
		if err != nil {
			continue
		}
		for _, e := range entries {
			if e.IsDir() || e.Name() == TakeoverFileName || !cd.allows(e.Name()) {
				continue
			}
			if b, err := readCapped(filepath.Join(cd.Dir, e.Name())); err == nil && hasLogOption(b) {
				return true
			}
		}
	}
	return false
}

// planLog 决定这次要不要加查询日志:返回要写的日志文件(空 = 不加)和不加的原因(空 = 没有原因,比如没配 QueryLog)。
// prev 是上次接管留下的状态(hasPrev 为假表示没有):上次因为 failed 去掉过,在撤销之前就不再试。
func (t *DNSTakeover) planLog(d discovery, prev takeoverState, hasPrev bool) (logPath, skip string) {
	p := strings.TrimSpace(t.QueryLog)
	if p == "" {
		return "", ""
	}
	if hasPrev && prev.LogSkip == LogSkipFailed {
		return "", LogSkipFailed
	}
	if err := validLogPath(p); err != nil {
		slog.Warn("查询日志路径不能用,接管时不开查询日志", "path", p, "error", err)
		return "", LogSkipFailed
	}
	if st, err := os.Stat(filepath.Dir(p)); err != nil || !st.IsDir() {
		slog.Warn("查询日志所在目录不存在,接管时不开查询日志", "path", p)
		return "", LogSkipFailed
	}
	if t.userSetsLogging(d) {
		return "", LogSkipUser
	}
	return p, ""
}

// ---- 找 dnsmasq 的配置目录 ----

type confDir struct {
	Dir     string
	Filters []string
}

// parseConfDirs 读 dnsmasq 主配置文本里的 conf-dir=<目录>[,过滤...]。
func parseConfDirs(text string) []confDir {
	var out []confDir
	for _, line := range strings.Split(text, "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		k, v, ok := strings.Cut(line, "=")
		if !ok || strings.TrimSpace(k) != "conf-dir" {
			continue
		}
		if cd, ok := splitDirFilters(v); ok {
			out = append(out, cd)
		}
	}
	return out
}

// parseDefaultsConfigDir 读 Debian /etc/default/dnsmasq 里的 CONFIG_DIR=(可带引号)。
func parseDefaultsConfigDir(text string) []confDir {
	var out []confDir
	for _, line := range strings.Split(text, "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		k, v, ok := strings.Cut(line, "=")
		if !ok || strings.TrimSpace(k) != "CONFIG_DIR" {
			continue
		}
		v = strings.Trim(strings.TrimSpace(v), `"'`)
		if cd, ok := splitDirFilters(v); ok {
			out = append(out, cd)
		}
	}
	return out
}

func splitDirFilters(v string) (confDir, bool) {
	parts := strings.Split(v, ",")
	dir := strings.TrimSpace(parts[0])
	if dir == "" || !filepath.IsAbs(dir) {
		return confDir{}, false
	}
	cd := confDir{Dir: filepath.Clean(dir)}
	for _, f := range parts[1:] {
		if f = strings.TrimSpace(f); f != "" {
			cd.Filters = append(cd.Filters, f)
		}
	}
	return cd, true
}

// allows 按 dnsmasq 的规则判断过滤器会不会放过这个文件名:以 * 开头的是「只读匹配的」,其余是「跳过这些后缀」。
func (c confDir) allows(name string) bool {
	var includes []string
	for _, f := range c.Filters {
		if strings.HasPrefix(f, "*") {
			includes = append(includes, f)
		} else if strings.HasSuffix(name, f) {
			return false
		}
	}
	if len(includes) == 0 {
		return true
	}
	for _, p := range includes {
		if ok, _ := path.Match(p, name); ok {
			return true
		}
	}
	return false
}

type discovery struct {
	Files    []string // 要放接管文件的完整路径(已去重、排序)
	Warnings []string
	Reason   string // Files 为空时的原因

	mainTexts []string  // 读到的主配置文本(找用户自己的日志设置用)
	dirs      []confDir // 全部配置目录(去重前的原样,含过滤规则)
}

func readCapped(p string) (string, error) {
	f, err := os.Open(p)
	if err != nil {
		return "", err
	}
	defer f.Close()
	b, err := io.ReadAll(io.LimitReader(f, maxConfRead))
	return string(b), err
}

// discover 只读:从 dnsmasq 自己的主配置里找它会读的配置目录。
func (t *DNSTakeover) discover() discovery {
	var dirs []confDir
	var warns []string
	var skipped []string
	var mainTexts []string
	seenMain := map[string]bool{}
	readable := 0
	for _, g := range t.mainConfigs() {
		matches, _ := filepath.Glob(g)
		sort.Strings(matches)
		for _, m := range matches {
			if seenMain[m] {
				continue
			}
			seenMain[m] = true
			text, err := readCapped(m)
			if err != nil {
				continue
			}
			readable++
			mainTexts = append(mainTexts, text)
			dirs = append(dirs, parseConfDirs(text)...)
			for _, line := range strings.Split(text, "\n") {
				line = strings.TrimSpace(line)
				if k, v, ok := strings.Cut(line, "="); ok && strings.TrimSpace(k) == "server" && !strings.HasPrefix(strings.TrimSpace(v), "/") {
					warns = append(warns, "dnsmasq 主配置里还有别的全局上游 server="+strings.TrimSpace(v)+",一部分查询可能绕过内核")
				}
			}
		}
	}
	if text, err := readCapped(t.defaultsFile()); err == nil {
		dirs = append(dirs, parseDefaultsConfigDir(text)...)
	}
	seen := map[string]bool{}
	var files []string
	for _, d := range dirs {
		if seen[d.Dir] {
			continue
		}
		seen[d.Dir] = true
		if !d.allows(TakeoverFileName) {
			skipped = append(skipped, d.Dir+"(过滤规则不读 "+TakeoverFileName+")")
			continue
		}
		if st, err := os.Stat(d.Dir); err != nil || !st.IsDir() {
			skipped = append(skipped, d.Dir+"(目录不存在)")
			continue
		}
		files = append(files, filepath.Join(d.Dir, TakeoverFileName))
	}
	sort.Strings(files)
	r := ""
	if len(files) == 0 {
		switch {
		case readable == 0 && len(dirs) == 0:
			r = "找不到 dnsmasq 的主配置,不知道它读哪个配置目录"
		case len(skipped) > 0:
			r = "dnsmasq 的配置目录都不能用:" + strings.Join(skipped, "、")
		default:
			r = "dnsmasq 的主配置里没有 conf-dir,不知道往哪放接管文件"
		}
	}
	return discovery{Files: files, Warnings: dedup(warns), Reason: r, mainTexts: mainTexts, dirs: dirs}
}

func dedup(in []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, s := range in {
		if !seen[s] {
			seen[s] = true
			out = append(out, s)
		}
	}
	return out
}

// ---- 状态文件 ----

func (t *DNSTakeover) loadState() (takeoverState, bool) {
	b, err := os.ReadFile(t.StateFile)
	if err != nil {
		return takeoverState{}, false
	}
	var st takeoverState
	if json.Unmarshal(b, &st) != nil || st.Version != 1 {
		return takeoverState{}, false
	}
	return st, true
}

func (t *DNSTakeover) saveState(st takeoverState) error {
	st.Version, st.At = 1, t.now().Unix()
	b, err := json.Marshal(st)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(t.StateFile), 0o700); err != nil {
		return err
	}
	return store.WriteFileAtomic(t.StateFile, b, 0o600)
}

func (t *DNSTakeover) clearState() error {
	if err := os.Remove(t.StateFile); err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	return nil
}

// ---- 文件与服务 ----

func isOurs(p string) bool {
	b, err := readCapped(p)
	return err == nil && strings.HasPrefix(b, takeoverMarker)
}

// removeOurs 删掉带标记的文件,返回真的删掉了几个。文件不存在不算错;同名但没有标记的不碰。
func removeOurs(files []string) (removed int, err error) {
	for _, p := range files {
		if _, statErr := os.Stat(p); statErr != nil {
			continue
		}
		if !isOurs(p) {
			continue
		}
		if e := os.Remove(p); e != nil && !errors.Is(e, os.ErrNotExist) {
			err = errors.Join(err, e)
			continue
		}
		removed++
	}
	return removed, err
}

func (t *DNSTakeover) restart(ctx context.Context) error {
	res, err := t.Services.Do(ctx, takeoverService, "restart")
	if err != nil {
		return fmt.Errorf("重启 dnsmasq 失败: %w", err)
	}
	if !res.OK {
		return fmt.Errorf("重启 dnsmasq 失败(退出码 %d): %s", res.Code, res.Stderr)
	}
	return nil
}

// waitHealthy 轮询 dnsmasq 的监听地址,直到它应答或超时。
func (t *DNSTakeover) waitHealthy(ctx context.Context) error {
	deadline := time.Now().Add(t.healthWait())
	var last error
	for {
		if last = t.probe(ctx, t.dnsmasqAddr()); last == nil {
			return nil
		}
		if time.Now().After(deadline) {
			return last
		}
		select {
		case <-ctx.Done():
			return ctx.Err()
		case <-time.After(250 * time.Millisecond):
		}
	}
}

func (t *DNSTakeover) inSync(files []string, content string) bool {
	if len(files) == 0 {
		return false
	}
	for _, p := range files {
		b, err := readCapped(p)
		if err != nil || b != content {
			return false
		}
	}
	return true
}

func (t *DNSTakeover) running(ctx context.Context) (bool, error) {
	info, err := t.Services.Status(ctx, takeoverService)
	if err != nil {
		return false, err
	}
	return info.Running, nil
}

// ---- 对外接口 ----

// Status 只读,不改任何东西。
func (t *DNSTakeover) Status(ctx context.Context) TakeoverStatus {
	t.mu.Lock()
	defer t.mu.Unlock()
	d := t.discover()
	st := TakeoverStatus{Dirs: dirsOf(d.Files), Warnings: d.Warnings}
	if len(d.Files) == 0 {
		st.Reason = d.Reason
		return st
	}
	run, err := t.running(ctx)
	switch {
	case err != nil:
		st.Reason = "查不到 dnsmasq 的状态: " + err.Error()
	case !run:
		st.Reason = "dnsmasq 没在运行"
	default:
		st.Supported = true
	}
	// 接管文件里带不带查询日志两行,以状态里记的为准
	if s, ok := t.loadState(); ok && s.Phase == phaseApplied {
		if c, err := t.contentFor(s.Log); err == nil && t.inSync(d.Files, c) {
			st.Applied = true
		}
	}
	return st
}

func dirsOf(files []string) []string {
	out := make([]string, 0, len(files))
	for _, f := range files {
		out = append(out, filepath.Dir(f))
	}
	return out
}

// Apply 让 dnsmasq 把全部查询交给内核的 DNS 入站(配了 QueryLog 还会顺带打开查询日志,见文件头)。
// changed 为假表示早已是这个状态、什么都没动。
// 出错时系统保持(或已恢复到)接管之前的状态;恢复不了会在错误里说明,并保留状态文件供 Recover 重试。
func (t *DNSTakeover) Apply(ctx context.Context) (changed bool, err error) {
	t.mu.Lock()
	defer t.mu.Unlock()

	if _, err := t.content(); err != nil {
		return false, err
	}
	d := t.discover()
	if len(d.Files) == 0 {
		return false, fmt.Errorf("%w:%s", ErrTakeoverUnsupported, d.Reason)
	}
	run, err := t.running(ctx)
	if err != nil {
		return false, fmt.Errorf("查不到 dnsmasq 的状态,不改 DNS: %w", err)
	}
	if !run {
		return false, fmt.Errorf("%w:dnsmasq 没在运行(这台机器的局域网 DNS 不是 dnsmasq 的话,请改用 hijack 模式)", ErrTakeoverUnsupported)
	}
	// 内核的 DNS 入站不答,就别把 dnsmasq 指过去——那会让整个局域网没有 DNS
	if err := t.probe(ctx, t.kernelAddr()); err != nil {
		return false, fmt.Errorf("内核的 DNS 入站(%s)没有应答,先让内核跑起来再接管 DNS,没有改任何设置: %w", t.kernelAddr(), &kernelDNSDownError{cause: err})
	}
	prev, hasPrev := t.loadState()
	logPath, skip := t.planLog(d, prev, hasPrev)
	content, err := t.contentFor(logPath)
	if err != nil {
		return false, err
	}
	if hasPrev && prev.Phase == phaseApplied && t.inSync(d.Files, content) && t.probe(ctx, t.dnsmasqAddr()) == nil {
		// 文件已经是对的:只有状态里记的日志情况变了(例如 failed 变成 user)才更新记录,不动 dnsmasq
		if prev.LogSkip != skip || prev.Log != logPath {
			_ = t.saveState(takeoverState{Phase: phaseApplied, Files: d.Files, Kernel: t.kernelAddr(), Log: logPath, LogSkip: skip})
		}
		return false, nil
	}

	// 先记下要动哪些文件,再动
	if err := t.saveState(takeoverState{Phase: phaseApplying, Files: d.Files, Kernel: t.kernelAddr(), Log: logPath, LogSkip: skip}); err != nil {
		return false, fmt.Errorf("写状态文件失败,没有改 DNS: %w", err)
	}
	restarted, err := t.install(ctx, d.Files, content)
	if err != nil && logPath != "" {
		// 带着查询日志没成:去掉日志那两行再来一次,接管本身还是要的
		slog.Warn("加了查询日志后 dnsmasq 没起来,去掉查询日志再试一次", "error", err)
		first := err
		logPath, skip = "", LogSkipFailed
		plain, cerr := t.contentFor("")
		if cerr != nil {
			return false, t.rollback(ctx, d.Files, restarted, cerr)
		}
		if serr := t.saveState(takeoverState{Phase: phaseApplying, Files: d.Files, Kernel: t.kernelAddr(), LogSkip: skip}); serr != nil {
			return false, t.rollback(ctx, d.Files, restarted, fmt.Errorf("写状态文件失败: %w", serr))
		}
		var again bool
		again, err = t.install(ctx, d.Files, plain)
		restarted = restarted || again
		if err != nil {
			err = fmt.Errorf("%w(带查询日志的那一次:%v)", err, first)
		}
	}
	if err != nil {
		return false, t.rollback(ctx, d.Files, restarted, err)
	}
	if err := t.saveState(takeoverState{Phase: phaseApplied, Files: d.Files, Kernel: t.kernelAddr(), Log: logPath, LogSkip: skip}); err != nil {
		// 已经生效,只是没记上:撤销时扫描目录也能找到带标记的文件,不算失败
		return true, nil
	}
	return true, nil
}

// install 把 content 写进每个接管文件、重启 dnsmasq、等它应答。出错时不撤销(由调用方决定);
// restarted 为真表示 dnsmasq 已经被重启过(可能读过新文件),撤销后要再重启一次。
func (t *DNSTakeover) install(ctx context.Context, files []string, content string) (restarted bool, err error) {
	for _, p := range files {
		if err := t.writeFile(p, []byte(content), 0o644); err != nil {
			return false, fmt.Errorf("写 %s 失败: %w", p, err)
		}
	}
	if err := t.restart(ctx); err != nil {
		return true, err
	}
	if err := t.waitHealthy(ctx); err != nil {
		return true, fmt.Errorf("接管后 dnsmasq 不再应答 DNS: %w", err)
	}
	return true, nil
}

// QueryLogState 读上次接管留下的状态:path 是让 dnsmasq 写查询日志的文件(空 = 没加),
// skip 是没加的原因(LogSkipUser / LogSkipFailed,空 = 没有原因)。没有接管状态时都是空。
func (t *DNSTakeover) QueryLogState() (path, skip string) {
	t.mu.Lock()
	defer t.mu.Unlock()
	st, ok := t.loadState()
	if !ok || st.Phase != phaseApplied {
		return "", ""
	}
	return st.Log, st.LogSkip
}

// LogOwned 报告 p 是不是我们让 dnsmasq 写的查询日志(接管已生效、状态里记的就是它):
// 只有这时后端才可以把它清空限大小,用户自己指定的日志文件不碰。
func (t *DNSTakeover) LogOwned(p string) bool {
	if strings.TrimSpace(p) == "" {
		return false
	}
	path, _ := t.QueryLogState()
	return path != "" && path == strings.TrimSpace(p)
}

// rollback 撤销一次没成功的 Apply。restarted 为真表示 dnsmasq 已经读过新文件,撤销后要再重启一次。
// 返回的错误以 cause 开头;撤销本身也失败时追加说明,并保留状态文件。
func (t *DNSTakeover) rollback(ctx context.Context, files []string, restarted bool, cause error) error {
	// 取消的 ctx 不能挡住回滚:改用一个新的、有上限的
	rctx, cancel := context.WithTimeout(context.WithoutCancel(ctx), 90*time.Second)
	defer cancel()
	if _, err := removeOurs(files); err != nil {
		return fmt.Errorf("%w;撤销时删除接管文件失败,请检查 %s: %v", cause, strings.Join(files, "、"), err)
	}
	if restarted {
		if err := t.restart(rctx); err != nil {
			return fmt.Errorf("%w;已删除接管文件但重启 dnsmasq 回到原状失败,请手动重启 dnsmasq: %v", cause, err)
		}
		if err := t.waitHealthy(rctx); err != nil {
			return fmt.Errorf("%w;已撤销接管,但 dnsmasq 仍没有应答,请手动检查 dnsmasq: %v", cause, err)
		}
	}
	if err := t.clearState(); err != nil {
		return fmt.Errorf("%w;已撤销接管,但清理状态文件失败: %v", cause, err)
	}
	return fmt.Errorf("%w(已自动撤销,DNS 回到接管之前的状态)", cause)
}

// Revert 撤销接管:删掉带标记的文件、重启 dnsmasq、清状态。没接管过也可以调用(什么都不做)。
func (t *DNSTakeover) Revert(ctx context.Context) error {
	t.mu.Lock()
	defer t.mu.Unlock()
	return t.revertLocked(ctx)
}

func (t *DNSTakeover) revertLocked(ctx context.Context) error {
	st, hasState := t.loadState()
	files := append([]string{}, st.Files...)
	// 状态文件丢了也要能清:再扫一遍 dnsmasq 会读的目录(只认带标记的)
	files = append(files, t.discover().Files...)
	files = dedup(files)
	removed, err := removeOurs(files)
	if err != nil {
		return fmt.Errorf("删除接管文件失败,请检查 %s: %w", strings.Join(files, "、"), err)
	}
	if removed > 0 {
		run, rerr := t.running(ctx)
		if rerr != nil || run { // 查不到状态时也试着重启:宁可多重启一次
			if err := t.restart(ctx); err != nil {
				return fmt.Errorf("已删除接管文件,但%w;请手动重启 dnsmasq", err)
			}
			if err := t.waitHealthy(ctx); err != nil {
				return fmt.Errorf("已删除接管文件并重启了 dnsmasq,但它仍没有应答: %w", err)
			}
		}
	}
	// 日志不再有人写了:把我们让 dnsmasq 写的那个文件删掉(只删状态里记的、普通的 .log 文件,别的不碰)
	removeOurLog(st.Log)
	if hasState || removed > 0 {
		if err := t.clearState(); err != nil {
			return fmt.Errorf("清理状态文件失败: %w", err)
		}
	}
	return nil
}

// removeOurLog 尽力删掉接管时让 dnsmasq 写的查询日志。状态文件是 root 才写得了的,但仍然只删普通文件、名字以 .log 结尾的。
func removeOurLog(p string) {
	if p == "" || validLogPath(p) != nil || !strings.HasSuffix(p, ".log") {
		return
	}
	if fi, err := os.Lstat(p); err == nil && fi.Mode().IsRegular() {
		_ = os.Remove(p)
	}
}

// Sync 按档案的 dns.mode 对齐系统:dnsmasq → Apply;off / hijack → Revert;别的值当作错误,不动系统。
// 部署成功之后、内核启动之后由 internal/dnssync 调用它;停止 / 重启内核前先 Revert。
func (t *DNSTakeover) Sync(ctx context.Context, mode string) (changed bool, err error) {
	switch mode {
	case "dnsmasq":
		return t.Apply(ctx)
	case "off", "hijack":
		t.mu.Lock()
		defer t.mu.Unlock()
		_, had := t.loadState()
		if err := t.revertLocked(ctx); err != nil {
			return false, err
		}
		return had, nil
	}
	return false, fmt.Errorf("不认识的 DNS 模式 %q", mode)
}

// Recover 给进程启动时用:清掉上次异常退出遗留的接管。
//   - 没有状态文件、目录里也没有带标记的文件:什么都不做;
//   - 状态是「应用到一半」:一律撤销(不知道 dnsmasq 此刻读到了什么);
//   - 状态是「已应用」且内核的 DNS 入站有应答:保留(内核正常,后端只是重启了);
//   - 内核没应答:撤销,免得 dnsmasq 一直指着一个不在的内核。
func (t *DNSTakeover) Recover(ctx context.Context) error {
	t.mu.Lock()
	defer t.mu.Unlock()
	st, has := t.loadState()
	leftover := false
	for _, f := range t.discover().Files {
		if isOurs(f) {
			leftover = true
		}
	}
	if !has && !leftover {
		return nil
	}
	if has && st.Phase == phaseApplied && t.probe(ctx, t.kernelAddr()) == nil {
		return nil
	}
	return t.revertLocked(ctx)
}
